import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { discoverPluginPackageRecords } from './discovery.mjs'

const repositoryRoot = fileURLToPath(new URL('../../', import.meta.url))
const outputPath = path.join(repositoryRoot, '.woe/plugin-map.md')

function join(values) {
  return values.filter(Boolean).join(', ') || '-'
}

function backendSummary(backend = {}) {
  return join(Object.entries(backend).map(([kind, value]) => {
    if (value && typeof value === 'object') {
      const entry = value.entry ?? value.staticExport ?? value.runtimeExport
      const exported = value.export ?? value.runtimeExport
      return `${kind}(${entry ?? '?'}${exported ? `#${exported}` : ''})`
    }
    return `${kind}(${String(value)})`
  }))
}

function frontendSummary(frontend = {}) {
  const slots = ['configEditor', 'messageActions', 'adminPanel', 'clientPlatformLabels']
    .filter(key => frontend[key] !== undefined)
    .map(key => `${key}=${typeof frontend[key] === 'string' ? frontend[key] : 'declared'}`)
  const locales = frontend.locales ? Object.keys(frontend.locales) : []
  return join([...slots, locales.length > 0 ? `locales=${locales.join('/')}` : ''])
}

function resourceSummary(resources = {}) {
  const bindings = (resources.bindings ?? []).map(binding => `${binding.name}:${binding.kind}`)
  const queues = (resources.queues ?? []).map(queue => queue.logicalResource ?? 'queue')
  return join([...bindings, ...queues.map(queue => `queue:${queue}`)])
}

const records = discoverPluginPackageRecords({
  rootDir: repositoryRoot,
  packageRoot: 'src/plugins/builtin'
})

const lines = [
  '# Plugin Map',
  '',
  'Generated by `npm run plugin:map`. Do not edit manually.',
  '',
  '| slug | module | capabilities | backend | frontend |',
  '| --- | --- | --- | --- | --- |',
  ...records.map(record => {
    const manifest = record.manifest
    return `| \`${record.slug}\` | \`${manifest.modulePath}\` | ${join(manifest.capabilities)} | ${backendSummary(manifest.backend)} | ${frontendSummary(manifest.frontend)} |`
  }),
  ''
]

for (const record of records) {
  const manifest = record.manifest
  lines.push(
    `## ${record.slug}`,
    '',
    `- Directory: \`${path.relative(repositoryRoot, record.packageDir).split(path.sep).join('/')}\``,
    `- Module: \`${manifest.modulePath}\``,
    `- Capabilities: ${join(manifest.capabilities)}`,
    `- Backend: ${backendSummary(manifest.backend)}`,
    `- Config parser: ${manifest.config?.parser ? `\`${manifest.config.parser.entry}#${manifest.config.parser.export}\`` : '-'}`,
    `- Secret fields: ${join(manifest.config?.secretFields ?? [])}`,
    `- Frontend: ${frontendSummary(manifest.frontend)}`,
    `- Resources: ${resourceSummary(manifest.resources)}`,
    `- Tests: \`npm run plugin:test -- ${record.slug}\``,
    ''
  )
}

mkdirSync(path.dirname(outputPath), { recursive: true })
writeFileSync(outputPath, `${lines.join('\n')}\n`)
console.log(`[plugin:map] wrote ${path.relative(repositoryRoot, outputPath)} (${records.length} packages)`)
