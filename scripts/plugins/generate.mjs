import { createHash } from 'node:crypto'
import {
  existsSync,
  lstatSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  renameSync,
  rmSync,
  writeFileSync
} from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { pluginPackageError } from './manifest.mjs'
import { discoverPluginPackageRecords } from './discovery.mjs'

const repositoryRoot = fileURLToPath(new URL('../../', import.meta.url))
const publicAssetsRoot = 'frontend/public/generated-plugins'
const outputRoots = [
  'src/generated/plugins',
  'frontend/src/generated/plugins',
  publicAssetsRoot
]
let temporarySequence = 0

function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize)
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.keys(value).sort().map(key => [key, canonicalize(value[key])]))
  }
  return value
}

function json(value) {
  return JSON.stringify(canonicalize(value), null, 2)
}

function moduleDescriptor(manifest) {
  const task = manifest.backend?.task
  const descriptor = {
    modulePath: manifest.modulePath,
    name: manifest.name,
    capabilities: manifest.capabilities,
    author: manifest.author,
    license: manifest.license,
    website: manifest.website,
    secretFields: manifest.config?.secretFields ?? []
  }
  if (manifest.config?.errorDescription !== undefined) {
    descriptor.configErrorDescription = manifest.config.errorDescription
  }
  if (task) {
    descriptor.task = {
      supportedSubjectTypes: task.supportedSubjectTypes,
      ...(task.quotaNamespace === undefined ? {} : { quotaNamespace: task.quotaNamespace }),
      ...(task.manualTrigger === undefined ? {} : { manualTrigger: task.manualTrigger }),
      ...(task.outbound === undefined ? {} : { outbound: task.outbound })
    }
  }
  if (manifest.backend?.push) descriptor.push = { platform: manifest.backend.push.platform }
  if (manifest.frontend !== undefined) descriptor.frontend = frontendMetadata(manifest.frontend)
  if (manifest.resources !== undefined) descriptor.resources = manifest.resources
  if (manifest.dependencies !== undefined) descriptor.dependencies = manifest.dependencies
  return descriptor
}

function frontendMetadata(frontend) {
  const descriptor = {}
  for (const field of ['configEditor', 'messageActions', 'adminPanel', 'clientPlatformLabels', 'locales']) {
    if (frontend[field] !== undefined) descriptor[field] = frontend[field]
  }
  return descriptor
}

function frontendDescriptor(manifest) {
  const descriptor = {
    modulePath: manifest.modulePath,
    capabilities: manifest.capabilities,
    platforms: manifest.backend?.push ? [manifest.backend.push.platform] : []
  }
  if (manifest.backend?.task?.quotaNamespace !== undefined) {
    descriptor.quotaNamespace = manifest.backend.task.quotaNamespace
  }
  if (manifest.frontend !== undefined) descriptor.frontend = frontendMetadata(manifest.frontend)
  return descriptor
}

function header(fingerprint) {
  return `// Generated by scripts/plugins/generate.mjs. Do not edit.\nexport const pluginGenerationFingerprint = ${JSON.stringify(fingerprint)}\n\n`
}

function renderServerCatalog(records, fingerprint) {
  const descriptors = records.map(record => moduleDescriptor(record.manifest))
  return `${header(fingerprint)}import type { ModuleDescriptor } from '../../plugins/moduleCatalog.ts'\n\nexport const moduleDescriptors: readonly ModuleDescriptor[] = ${json(descriptors)}\n`
}

function renderFrontendCatalog(records, fingerprint) {
  const descriptors = records.map(record => frontendDescriptor(record.manifest))
  return `${header(fingerprint)}export interface FrontendDescriptor {\n  configEditor?: string\n  messageActions?: string\n  adminPanel?: string\n  clientPlatformLabels?: Readonly<Record<string, string>>\n  locales?: Partial<Record<'en-US' | 'zh-CN', string>>\n}\n\nexport interface FrontendModuleDescriptor {\n  modulePath: string\n  capabilities: readonly string[]\n  quotaNamespace?: string\n  platforms: readonly string[]\n  frontend?: FrontendDescriptor\n}\n\nexport const frontendModuleDescriptors: readonly FrontendModuleDescriptor[] = ${json(descriptors)}\n`
}

function importSpecifier(fromFile, targetFile) {
  const relative = path.relative(path.dirname(fromFile), targetFile).split(path.sep).join('/')
  return relative.startsWith('.') ? relative : `./${relative}`
}

function renderServerEntries(rootDir, records, fingerprint) {
  const outputFile = path.join(rootDir, 'src/generated/plugins/server.ts')
  const aliases = new Map()
  const imports = []
  const entryAlias = (packageDir, entry) => {
    const target = path.resolve(packageDir, entry)
    if (!aliases.has(target)) {
      const alias = `pluginEntry${aliases.size}`
      aliases.set(target, alias)
      imports.push(`import * as ${alias} from ${JSON.stringify(importSpecifier(outputFile, target))}`)
    }
    return aliases.get(target)
  }

  const modules = records.map(record => {
    const { manifest, packageDir } = record
    const properties = []
    if (manifest.backend?.event) {
      const alias = entryAlias(packageDir, manifest.backend.event.entry)
      properties.push(`    event: ${alias}.${manifest.backend.event.export}`)
    }
    if (manifest.backend?.task) {
      const alias = entryAlias(packageDir, manifest.backend.task.entry)
      properties.push(`    task: {\n      staticFactory: ${alias}.${manifest.backend.task.staticExport},\n      runtimeFactory: ${alias}.${manifest.backend.task.runtimeExport}\n    }`)
    }
    if (manifest.backend?.push) {
      const alias = entryAlias(packageDir, manifest.backend.push.entry)
      properties.push(`    push: ${alias}.${manifest.backend.push.export}`)
    }
    if (manifest.config?.parser) {
      const alias = entryAlias(packageDir, manifest.config.parser.entry)
      properties.push(`    configParser: ${alias}.${manifest.config.parser.export}`)
    }
    return `  ${JSON.stringify(manifest.modulePath)}: {\n${properties.join(',\n')}\n  }`
  })
  return `${header(fingerprint)}${imports.join('\n')}${imports.length ? '\n\n' : ''}export const serverModules = {\n${modules.join(',\n')}\n} as const\n`
}

function renderUi(rootDir, records, fingerprint) {
  const outputFile = path.join(rootDir, 'frontend/src/generated/plugins/ui.ts')
  const modules = records.map(record => {
    const properties = []
    for (const field of ['configEditor', 'messageActions', 'adminPanel']) {
      const entry = record.manifest.frontend?.[field]
      if (entry !== undefined) {
        const specifier = importSpecifier(outputFile, path.resolve(record.packageDir, entry))
        properties.push(`    ${field}: () => import(${JSON.stringify(specifier)})`)
      }
    }
    return `  ${JSON.stringify(record.manifest.modulePath)}: {\n${properties.join(',\n')}\n  }`
  })
  return `${header(fingerprint)}export const pluginUiLoaders = {\n${modules.join(',\n')}\n} as const\n`
}

function renderLocales(rootDir, records, fingerprint) {
  const outputFile = path.join(rootDir, 'frontend/src/generated/plugins/locales.ts')
  const imports = []
  const contributions = { 'en-US': [], 'zh-CN': [] }
  for (const record of records) {
    for (const locale of ['en-US', 'zh-CN']) {
      const entry = record.manifest.frontend?.locales?.[locale]
      if (entry === undefined) continue
      const alias = `pluginLocale${imports.length}`
      imports.push(
        `import ${alias} from ${JSON.stringify(importSpecifier(outputFile, path.resolve(record.packageDir, entry)))}`
      )
      contributions[locale].push(alias)
    }
  }
  const perLocale = ['en-US', 'zh-CN'].map(locale => {
    const items = contributions[locale]
    if (items.length === 0) return `  ${JSON.stringify(locale)}: []`
    return `  ${JSON.stringify(locale)}: [\n${items.map(alias => `    ${alias}`).join(',\n')}\n  ]`
  })
  return (
    `${header(fingerprint)}${imports.join('\n')}${imports.length ? '\n\n' : ''}` +
    'export const pluginLocaleMessages: Readonly<\n' +
    "  Record<'en-US' | 'zh-CN', readonly Record<string, unknown>[]>\n" +
    '> = {\n' +
    `${perLocale.join(',\n')}\n` +
    '}\n'
  )
}








async function collectLocaleContributions(rootDir, records) {
  const seenNodes = { 'en-US': new Map(), 'zh-CN': new Map() }
  for (const locale of ['en-US', 'zh-CN']) {
    const coreFile = path.join(rootDir, 'frontend/src/locales', `${locale}.ts`)
    if (existsSync(coreFile)) {
      const loaded = await import(pathToFileURL(coreFile).href)
      for (const [key, kind] of localeNodes(loaded.default)) seenNodes[locale].set(key, { kind, owner: 'core' })
    }
  }

  for (const record of records) {
    for (const locale of ['en-US', 'zh-CN']) {
      const entry = record.manifest.frontend?.locales?.[locale]
      if (entry === undefined) continue
      const field = `frontend.locales.${locale}`
      const file = path.resolve(record.packageDir, entry)
      let messages
      try {
        const loaded = await import(pathToFileURL(file).href)
        messages = loaded.default
      } catch (error) {
        throw pluginPackageError(record.slug, field, `locale module failed to load: ${error.message}`)
      }
      if (
        messages === null ||
        typeof messages !== 'object' ||
        Array.isArray(messages)
      ) {
        throw pluginPackageError(record.slug, field, 'locale module must default-export a message object')
      }
      for (const [key, kind] of localeNodes(messages)) {
        const previous = seenNodes[locale].get(key)
        if (previous && (previous.kind !== 'object' || kind !== 'object')) {
          const source = previous.owner === 'core' ? 'the core frontend locale' : `package "${previous.owner}"`
          const reason = previous.kind === kind ? `duplicates ${source}` : `has a parent/leaf shape conflict with ${source}`
          throw pluginPackageError(record.slug, field, `locale key "${key}" ${reason}`)
        }
        if (!previous) seenNodes[locale].set(key, { kind, owner: record.slug })
      }
    }
  }
}


function localeNodes(value, prefix = '', nodes = new Map()) {
  const object = value !== null && typeof value === 'object' && !Array.isArray(value)
  if (prefix) nodes.set(prefix, object ? 'object' : 'leaf')
  if (object) {
    for (const [key, child] of Object.entries(value)) localeNodes(child, prefix ? `${prefix}.${key}` : key, nodes)
  }
  return nodes
}







function collectPackageAssets(records) {
  const assets = []
  for (const record of records) {
    const declared = record.manifest.assets
    if (declared === undefined) continue
    const sourceRoot = path.resolve(record.packageDir, declared)
    const addFile = (absolute, relativeInAssetRoot) => {
      assets.push({
        slug: record.slug,
        absolute,
        relative: `${record.slug}/${relativeInAssetRoot.split(path.sep).join('/')}`
      })
    }
    let stat
    try {
      stat = lstatSync(sourceRoot)
    } catch {
      throw pluginPackageError(record.slug, 'assets', `declared path does not exist: "${declared}"`)
    }
    if (stat.isFile()) {
      addFile(sourceRoot, path.basename(sourceRoot))
      continue
    }
    const visit = (directory, prefix) => {
      for (const entry of readdirSync(directory, { withFileTypes: true })) {
        const absolute = path.join(directory, entry.name)
        const relative = prefix ? `${prefix}/${entry.name}` : entry.name
        if (entry.isSymbolicLink()) {
          throw pluginPackageError(
            record.slug,
            'assets',
            `symlink is not allowed: "${declared}/${relative}"`
          )
        }
        if (entry.isDirectory()) visit(absolute, relative)
        else addFile(absolute, relative)
      }
    }
    visit(sourceRoot, '')
  }
  assets.sort((left, right) => (left.relative < right.relative ? -1 : left.relative > right.relative ? 1 : 0))
  return assets
}

function listFilesRecursively(rootDir, directory, prefix = '') {
  if (!existsSync(directory)) return []
  const files = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const absolute = path.join(directory, entry.name)
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name
    if (entry.isSymbolicLink()) {
      throw new Error(`Generated plugin output is stale: symlink found at ${absolute}`)
    }
    if (entry.isDirectory()) files.push(...listFilesRecursively(rootDir, absolute, relative))
    else files.push(path.relative(rootDir, absolute).split(path.sep).join('/'))
  }
  return files
}

function assertCurrent(rootDir, expected) {
  const expectedFiles = [...expected.keys()].sort()
  const actualFiles = new Set()
  if (existsSync(path.join(rootDir, '.plugin-generation.json'))) actualFiles.add('.plugin-generation.json')
  for (const outputRoot of outputRoots) {
    for (const file of listFilesRecursively(rootDir, path.join(rootDir, outputRoot))) actualFiles.add(file)
  }
  for (const file of expectedFiles) {
    const absolute = path.join(rootDir, file)
    if (!existsSync(absolute) || !lstatSync(absolute).isFile()) {
      throw new Error(`Generated plugin output is stale or missing at ${absolute}; run node scripts/plugins/generate.mjs`)
    }
    const actualContents = readFileSync(absolute)
    const expectedContents = expected.get(file)
    const matches = Buffer.isBuffer(expectedContents)
      ? actualContents.equals(expectedContents)
      : actualContents.toString('utf8') === expectedContents
    if (!matches) {
      throw new Error(`Generated plugin output is stale at ${absolute}; run node scripts/plugins/generate.mjs`)
    }
  }
  for (const file of actualFiles) {
    if (!expected.has(file)) {
      throw new Error(`Generated plugin output has an extra stale file at ${path.join(rootDir, file)}; run node scripts/plugins/generate.mjs`)
    }
  }
}

function replaceDirectory(target, temporary, scratchRoot) {
  const sequence = temporarySequence++
  const backup = path.join(scratchRoot, `${path.basename(target)}.backup-${process.pid}-${sequence}`)
  const existed = existsSync(target)
  if (existed) renameSync(target, backup)
  try {
    renameSync(temporary, target)
  } catch (error) {
    if (existed && !existsSync(target)) renameSync(backup, target)
    throw error
  }
  if (existed) rmSync(backup, { recursive: true, force: true })
}

function writeArtifacts(rootDir, expected) {
  const temporaries = []
  const outputTemporaries = new Map()
  const scratchRoot = path.join(rootDir, '.plugin-tmp')
  mkdirSync(scratchRoot, { recursive: true })
  try {
    for (const outputRoot of outputRoots) {
      const target = path.join(rootDir, outputRoot)
      mkdirSync(path.dirname(target), { recursive: true })
      const temporary = path.join(scratchRoot, `${path.basename(target)}.tmp-${process.pid}-${temporarySequence++}`)
      outputTemporaries.set(outputRoot, temporary)
      mkdirSync(temporary)
      temporaries.push(temporary)
      for (const [file, contents] of expected) {
        const relative = path.relative(outputRoot, file).split(path.sep).join('/')
        if (relative === '..' || relative.startsWith('../') || path.isAbsolute(relative)) continue
        const destination = path.join(temporary, relative)
        mkdirSync(path.dirname(destination), { recursive: true })
        writeFileSync(destination, contents)
      }
    }

    const fingerprintTarget = path.join(rootDir, '.plugin-generation.json')
    const fingerprintTemporary = path.join(scratchRoot, `fingerprint.tmp-${process.pid}-${temporarySequence++}`)
    writeFileSync(fingerprintTemporary, expected.get('.plugin-generation.json'))
    temporaries.push(fingerprintTemporary)

    for (const outputRoot of outputRoots) {
      const target = path.join(rootDir, outputRoot)
      const temporary = outputTemporaries.get(outputRoot)
      replaceDirectory(target, temporary, scratchRoot)
    }
    renameSync(fingerprintTemporary, fingerprintTarget)
  } finally {
    for (const temporary of temporaries) rmSync(temporary, { recursive: true, force: true })
  }
}

export async function generatePluginArtifacts({ rootDir, check = false }) {
  const absoluteRoot = path.resolve(rootDir)
  const records = discoverPluginPackageRecords({ rootDir: absoluteRoot, packageRoot: 'src/plugins/builtin' })
  await collectLocaleContributions(absoluteRoot, records)


  const assets = collectPackageAssets(records)
  const fingerprintInput = {
    records: records.map(record => ({ slug: record.slug, manifest: record.manifest })),
    assets: assets.map(asset => ({
      path: `${publicAssetsRoot}/${asset.relative}`,
      sha256: createHash('sha256').update(readFileSync(asset.absolute)).digest('hex')
    }))
  }
  const fingerprint = createHash('sha256').update(JSON.stringify(canonicalize(fingerprintInput))).digest('hex')
  const modules = records.map(record => record.manifest.modulePath)
  const files = [
    '.plugin-generation.json',
    'frontend/src/generated/plugins/catalog.ts',
    'frontend/src/generated/plugins/locales.ts',
    'frontend/src/generated/plugins/ui.ts',
    'src/generated/plugins/catalog.ts',
    'src/generated/plugins/server.ts',
    ...assets.map(asset => `${publicAssetsRoot}/${asset.relative}`)
  ].sort()
  const expected = new Map([
    ['src/generated/plugins/catalog.ts', renderServerCatalog(records, fingerprint)],
    ['src/generated/plugins/server.ts', renderServerEntries(absoluteRoot, records, fingerprint)],
    ['frontend/src/generated/plugins/catalog.ts', renderFrontendCatalog(records, fingerprint)],
    ['frontend/src/generated/plugins/ui.ts', renderUi(absoluteRoot, records, fingerprint)],
    ['frontend/src/generated/plugins/locales.ts', renderLocales(absoluteRoot, records, fingerprint)],
    ['.plugin-generation.json', `${json({ fingerprint, modules, files })}\n`],
    ...assets.map(asset => [`${publicAssetsRoot}/${asset.relative}`, readFileSync(asset.absolute)])
  ])

  if (check) {
    assertCurrent(absoluteRoot, expected)
  } else {

    try {
      assertCurrent(absoluteRoot, expected)
    } catch {
      writeArtifacts(absoluteRoot, expected)
    }
  }
  return { modules, fingerprint, files }
}

async function runCli() {
  const args = process.argv.slice(2)
  if (args.some(argument => argument !== '--check') || args.length > 1) {
    throw new Error('Usage: node scripts/plugins/generate.mjs [--check]')
  }



  const result = await generatePluginArtifacts({ rootDir: repositoryRoot, check: args.includes('--check') })
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  runCli().catch(error => {
    process.stderr.write(`${error.message}\n`)
    process.exitCode = 1
  })
}
